import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { test } from 'node:test';

const subject = 'fix(hooks)!: check commit metadata';

/** Run the public checker with an in-memory commit message. */
function check(message, options = []) {
  const result = spawnSync(
    'bash',
    [
      '-c',
      'cat | bash scripts/check-commit-msg.sh "$@" /dev/stdin',
      'check-commit-msg',
      ...options,
    ],
    { input: message, encoding: 'utf8' }
  );
  assert.ifError(result.error);
  return { status: result.status, output: result.stdout + result.stderr };
}

test('accepts valid subjects and scoped package names', () => {
  assert.equal(check(`${subject}\n\nUpdate \`@openkit/api\`.\n`, ['--']).status, 0);
  assert.equal(check(subject).status, 0);
  assert.equal(check('Invalid subject\n').status, 1);
  assert.equal(check('Merge a lane commit\n', ['--metadata-only']).status, 0);
});

test('distinguishes addresses from other at-sign uses in both checker modes', () => {
  const atSign = String.fromCharCode(64);
  const cases = [
    ['profile URL path', 'See https://example.invalid/@release', 0],
    ['profile URL query', 'See https://example.invalid/@release?tab=updates', 0],
    ['scoped npm package', 'pnpm add -D @scope/pkg', 0],
    ['pinned scoped npm package', 'pnpm add -D @biomejs/biome@2.6.6', 0],
    ['pinned unscoped npm package', 'pnpm add pkg@1.2.3', 0],
    ['versioned UNPKG URL', 'See https://unpkg.com/@biomejs/biome@2.6.6?meta', 0],
    ['GitHub mention', 'Notify `@mention` on the issue', 0],
    ['decorator', 'Add `@Component` to the view', 0],
    ['scoped package path', 'Inspect node_modules/@scope/pkg/package.json', 0],
    ['standalone address', `Contact synthetic${atSign}example.invalid.`, 1],
    ['address in a URL query', `See https://example.invalid/?to=synthetic${atSign}intranet`, 1],
  ];
  for (const [description, body, expected] of cases) {
    for (const options of [[], ['--metadata-only']]) {
      assert.equal(check(`${subject}\n\n${body}\n`, options).status, expected, description);
    }
  }
});

test('rejects prohibited trailers and harness signatures in both modes', () => {
  for (const line of [
    'cO-aUtHoReD-bY:',
    '  Signed-off-by:',
    'Generated by a harness',
    '- **Generated with** a harness',
    '🤖 Made with a harness',
    '1. Made with a harness',
    'Made-with: a harness',
    'Claude-Session: synthetic',
  ]) {
    for (const options of [[], ['--metadata-only']]) {
      assert.deepEqual(check(`${subject}\n\n${line}\n`, options), {
        status: 1,
        output: 'Commit message contains prohibited attribution metadata.\n',
      });
    }
  }
});

test('rejects address text in the subject or body without printing it', () => {
  const atSign = String.fromCharCode(64);
  for (const text of [
    `<synthetic+tag${atSign}invalid.test>`,
    `"quoted local"${atSign}intranet`,
    `synthetic/${atSign}intranet`,
    `synthetic${atSign}[192.0.2.1]`,
    `ø${atSign}例.invalid`,
    `https://example.invalid/@release?contact=synthetic${atSign}intranet`,
  ]) {
    for (const message of [`fix: mention ${text}\n`, `${subject}\n\n${text}`]) {
      const result = check(message);
      assert.equal(result.status, 1);
      assert.ok(
        result.output === 'Commit message contains prohibited attribution metadata.\n',
        'Address rejection must emit only the fixed diagnostic'
      );
    }
  }
});

test('fails closed on a missing message file', () => {
  const result = spawnSync(
    'bash',
    ['scripts/check-commit-msg.sh', '--metadata-only', '/dev/null/missing'],
    {
      encoding: 'utf8',
    }
  );
  assert.ifError(result.error);
  assert.equal(result.status, 2);
  assert.equal(result.stdout + result.stderr, 'Commit message could not be read.\n');
});
