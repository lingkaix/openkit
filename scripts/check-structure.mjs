#!/usr/bin/env node
/**
 * Structural-fitness check (docs/toolchain.md "Structural fitness").
 *
 * Blocking (precise): D1 shared-decision sites outside their owner (canonical JSON, digest
 * framing, the Workspace access denial) and D2 value-import edges inside a value-import cycle.
 * New keys or grown values against scripts/structure-baseline.json fail; `--update` only drops
 * vanished keys and lowers values. Keys never contain line numbers.
 *
 * Signals (never gate, no baseline): D4 cognitive complexity, D5 LCOM4 cohesion, D6
 * list-then-search, D7 pass-through units. `--report` prints their top items on demand.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript6';

/** Production roots. */
export const SCOPE_ROOTS = ['apps', 'packages'];

/** Registry owners: a decision is implemented only in its owner file. */
export const PRIMITIVE_OWNERS = {
  'canonical-json': ['packages/protocol/src/common/canonical-json.ts'],
  'digest-framing': ['packages/protocol/src/digest.ts'],
  'workspace-access-denial': ['apps/nanocore/src/operation-error.ts'],
};

export const BLOCKING = ['D1', 'D2'];
export const SIGNALS = ['D4', 'D5', 'D6', 'D7'];

/** Rounded p95 of cognitive complexity at pilot start (b440a144e); a report band, not a target. */
export const D4_BAND = 13;

const CANONICAL_NAME =
  /^(?:canonical|stable)\w*(?:Json|Stringify|JsonText|JsonValue)$|^stableStringify$|^canonicalize\w*Json\w*$|^sort\w*Keys$/;
/** The Workspace access denial code; its code, message and status live in WORKSPACE_ACCESS_DENIED. */
const DENIAL_CODE = 'workspace_access_denied';
const LIST_METHOD = /^list[A-Z]\w*$/;
const ITERATORS = new Set(['find', 'some', 'filter', 'findIndex', 'every']);
const SKIP_DIRS = new Set([
  'node_modules',
  'dist',
  'build',
  'target',
  '.next',
  'out',
  'coverage',
  'test-support',
  '__fixtures__',
  'e2e',
  'generated',
  'generated-schema',
]);
const GENERATED_HEADER = /@generated\b|DO NOT EDIT|auto-generated|autogenerated|Code generated/i;
const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_BASELINE = join(REPO_ROOT, 'scripts/structure-baseline.json');
const HINT = {
  D2: 'do not add a value-import edge inside the cycle',
  D4: 'cognitive complexity at or above the report band',
  D5: 'cohesion components',
  D6: 'list-then-search; prefer a keyed read',
  D7: 'pass-through unit',
};

/**
 * @param {string} repoRoot
 * @param {{ scopeRoots?: string[], owners?: typeof PRIMITIVE_OWNERS }} [options]
 */
export function analyzeStructure(repoRoot, options = {}) {
  const scopeRoots = options.scopeRoots ?? SCOPE_ROOTS;
  const owners = options.owners ?? PRIMITIVE_OWNERS;
  const files = collectFiles(repoRoot, scopeRoots);
  const findings = emptyFindings();
  const ctx = { owners, findings, valueImports: [], parseErrors: [] };

  const parsed = [];
  for (const rel of files) {
    const text = readFileSync(join(repoRoot, rel), 'utf8');
    if (GENERATED_HEADER.test(text.slice(0, 800))) continue;
    parsed.push(rel);
    const kind = rel.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
    const source = ts.createSourceFile(rel, text, ts.ScriptTarget.Latest, true, kind);
    if (source.parseDiagnostics.length > 0) ctx.parseErrors.push(rel);
    inspectFile(source, rel, ctx);
  }

  const valueEdges = resolveEdges(ctx.valueImports, new Set(parsed));
  addCycles(findings, valueEdges, tarjan(parsed, valueEdges));
  return { findings, files: parsed.length, parseErrors: ctx.parseErrors };
}

export function emptyBaseline() {
  return { D1: {}, D2: {} };
}

/** @param {ReturnType<typeof emptyFindings>} findings */
export function snapshotBaseline(findings) {
  const next = emptyBaseline();
  for (const detector of BLOCKING) {
    for (const key of Object.keys(findings[detector] ?? {}).sort()) {
      next[detector][key] = findings[detector][key].value;
    }
  }
  return next;
}

/** Drops vanished keys and lowers values. Never adds or raises. */
export function shrinkBaseline(baseline, findings) {
  const next = emptyBaseline();
  for (const detector of BLOCKING) {
    const current = findings[detector] ?? {};
    for (const key of Object.keys(baseline[detector] ?? {}).sort()) {
      if (!Object.hasOwn(current, key)) continue;
      const was = baseline[detector][key];
      const now = current[key].value;
      next[detector][key] = Math.min(now, was);
    }
  }
  return next;
}

export function evaluateBaseline(findings, baseline) {
  const violations = [];
  let shrinkable = 0;
  for (const detector of BLOCKING) {
    const current = findings[detector] ?? {};
    const base = baseline[detector] ?? {};
    for (const key of Object.keys(current).sort()) {
      const delta = deltaOf(detector, key, current[key], base);
      if (delta) violations.push(delta);
    }
    for (const key of Object.keys(base)) {
      if (!Object.hasOwn(current, key) || current[key].value < base[key]) shrinkable += 1;
    }
  }
  return { violations, shrinkable };
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.init && existsSync(args.baseline)) {
    console.error(`baseline already exists: ${args.baseline}`);
    return 2;
  }
  const result = analyzeStructure(args.root);
  for (const file of result.parseErrors) console.error(`unparseable: ${file}`);
  if (result.parseErrors.length > 0) return 1;
  if (args.report) {
    process.stdout.write(renderReport(result.findings));
    return 0;
  }
  if (args.init) {
    writeBaseline(args.baseline, snapshotBaseline(result.findings));
    return 0;
  }
  const baseline = readBaseline(args.baseline);
  const judged = evaluateBaseline(result.findings, baseline);
  if (args.update) writeBaseline(args.baseline, shrinkBaseline(baseline, result.findings));
  for (const item of judged.violations) console.log(formatDelta(item));
  const remaining = args.update ? 0 : judged.shrinkable;
  console.log(
    `structure: ${result.files} files, ${judged.violations.length} blocking, ${remaining} shrinkable`
  );
  return judged.violations.length > 0 ? 1 : 0;
}

function parseArgs(argv) {
  const args = {
    root: REPO_ROOT,
    baseline: DEFAULT_BASELINE,
    update: false,
    init: false,
    report: false,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--update') args.update = true;
    else if (arg === '--init') args.init = true;
    else if (arg === '--report') args.report = true;
    else if (arg === '--root') args.root = argv[++index] ?? '';
    else if (arg === '--baseline') args.baseline = argv[++index] ?? '';
    else {
      console.error(`unknown option ${arg}`);
      process.exit(2);
    }
  }
  if (!args.root || !args.baseline) {
    console.error('--root and --baseline need a value');
    process.exit(2);
  }
  return args;
}

function emptyFindings() {
  return { D1: {}, D2: {}, D4: {}, D5: {}, D6: {}, D7: {} };
}

function collectFiles(repoRoot, scopeRoots) {
  const files = [];
  for (const root of scopeRoots) {
    const abs = join(repoRoot, root);
    if (existsSync(abs)) walkDir(abs, repoRoot, files);
  }
  return files.sort();
}

function walkDir(abs, repoRoot, files) {
  for (const entry of readdirSync(abs, { withFileTypes: true })) {
    const full = join(abs, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) walkDir(full, repoRoot, files);
      continue;
    }
    if (entry.isFile() && isProduction(entry.name)) {
      files.push(relative(repoRoot, full).split(sep).join('/'));
    }
  }
}

function isProduction(name) {
  if (name.endsWith('.d.ts')) return false;
  if (!name.endsWith('.ts') && !name.endsWith('.tsx')) return false;
  if (/\.(?:test|fixture|spec)\.tsx?$/.test(name)) return false;
  return true;
}

function inspectFile(source, rel, ctx) {
  const anons = new Map();
  const file = {
    canonicalNames: new Set(),
    hashFns: [],
    forwarders: new Set(),
    topLevel: [],
    classFrames: [],
  };
  walk(source, '<module>');
  for (const item of file.hashFns) applyDigest(item, file.canonicalNames, source, rel, ctx);
  if (file.topLevel.length >= 10) addModuleUnit(source, rel, file.topLevel, ctx);
  addModuleForwarders(source, rel, file, ctx);

  function walk(node, symbol) {
    if (ts.isClassDeclaration(node) || ts.isClassExpression(node)) {
      handleClass(node, symbol);
      return;
    }
    if (isFn(node)) {
      handleFunction(node, symbol);
      return;
    }
    recordLoose(node, symbol, source, rel, ctx);
    ts.forEachChild(node, (child) => walk(child, symbol));
  }

  function handleClass(node, symbol) {
    const name = node.name
      ? joinSymbol(symbol, node.name.text)
      : joinSymbol(symbol, bindingName(node) ?? anon(symbol, anons));
    const frame = { name, node, methods: [] };
    file.classFrames.push(frame);
    ts.forEachChild(node, (child) => walk(child, name));
    file.classFrames.pop();
    buildClassUnit(frame, rel, source, ctx);
    if (symbol === '<module>') file.topLevel.push({ node, symbol: name, kind: 'class' });
  }

  function handleFunction(node, symbol) {
    if (!node.body) return;
    const name = fnSymbol(node, symbol, anons);
    const line = lineOf(source, node);
    const complexity = cognitive(node);
    const canonical = canonicalHit(node);
    if (complexity >= D4_BAND) {
      setMax(ctx.findings.D4, `${rel} :: ${name}`, site(rel, line, complexity, HINT.D4));
    }
    if (canonical) {
      for (const declared of declaredNames(node)) file.canonicalNames.add(declared);
      if (!owned(ctx.owners, 'canonical-json', rel)) {
        setOnce(
          ctx.findings.D1,
          `${rel} :: ${name} :: canonical-json`,
          site(rel, line, 1, hint('canonical-json', ctx.owners))
        );
      }
    }
    if (isForwarder(node)) {
      file.forwarders.add(name);
      setOnce(ctx.findings.D7, `${rel} :: ${name} :: forwarder`, site(rel, line, 1, HINT.D7));
    }
    scanScale(node, name, source, rel, ctx.findings);
    if (functionHasCreateHash(node)) file.hashFns.push({ node, symbol: name, line });
    const inners = directInnerFunctions(node);
    if (inners.length >= 5) buildFactoryUnit(node, name, inners, rel, source, ctx);
    const frame = file.classFrames.at(-1);
    if (frame && isClassMember(node)) {
      frame.methods.push({ name: memberLabel(node), node, ...collectThis(node) });
    }
    if (symbol === '<module>') file.topLevel.push({ node, symbol: name, kind: 'function' });
    ts.forEachChild(node, (child) => walk(child, name));
  }
}

function canonicalHit(node) {
  const byName = declaredNames(node).some((name) => CANONICAL_NAME.test(name));
  const byBody = canonicalBody(node);
  if (!byName && !byBody) return null;
  if (byName && byBody) return 'both';
  return byName ? 'name' : 'body';
}

function addModuleForwarders(source, rel, file, ctx) {
  if (!moduleIsPassthrough(source, file.forwarders)) return;
  setOnce(ctx.findings.D7, `${rel} :: <module> :: pass-through`, site(rel, 1, 1, HINT.D7));
}

function moduleIsPassthrough(source, forwarders) {
  let exports = 0;
  let ok = true;
  for (const stmt of source.statements) {
    if (ts.isExportDeclaration(stmt)) {
      const outcome = exportDeclarationOutcome(stmt, forwarders);
      exports += outcome.exports;
      if (!outcome.ok) ok = false;
      continue;
    }
    if (ts.isExportAssignment(stmt)) {
      exports += 1;
      const expr = unwrap(stmt.expression);
      const name = expr && isFn(expr) ? (bindingName(expr) ?? 'default') : '';
      if (!forwarders.has('default') && !forwarders.has(name)) ok = false;
      continue;
    }
    if (!hasExport(stmt)) continue;
    if (ts.isInterfaceDeclaration(stmt) || ts.isTypeAliasDeclaration(stmt)) continue;
    if (ts.isFunctionDeclaration(stmt)) {
      exports += 1;
      if (!stmt.name || !forwarders.has(stmt.name.text)) ok = false;
      continue;
    }
    if (ts.isVariableStatement(stmt)) {
      for (const decl of stmt.declarationList.declarations) {
        exports += 1;
        const name = ts.isIdentifier(decl.name) ? decl.name.text : '';
        if (!forwarders.has(name)) ok = false;
      }
      continue;
    }
    exports += 1;
    ok = false;
  }
  return exports > 0 && ok;
}

function exportDeclarationOutcome(stmt, forwarders) {
  if (stmt.isTypeOnly) return { exports: 0, ok: true };
  if (stmt.moduleSpecifier) return { exports: 1, ok: true };
  if (!stmt.exportClause || !ts.isNamedExports(stmt.exportClause)) return { exports: 1, ok: true };
  let exports = 0;
  let ok = true;
  for (const element of stmt.exportClause.elements) {
    if (element.isTypeOnly) continue;
    exports += 1;
    const local = element.propertyName ? element.propertyName.text : element.name.text;
    if (!forwarders.has(local)) ok = false;
  }
  return { exports, ok };
}

function isForwarder(fn) {
  if (!isFnExported(fn)) return false;
  const params = paramNames(fn);
  const call = forwardCall(fn);
  if (!call || !call.expression || !isIdentifier(call.expression)) return false;
  if (call.arguments.length !== params.length) return false;
  for (let index = 0; index < params.length; index += 1) {
    const arg = unwrap(call.arguments[index]);
    if (!arg || !isIdentifier(arg) || arg.text !== params[index]) return false;
  }
  return true;
}

function forwardCall(fn) {
  if (!fn.body) return null;
  if (!ts.isBlock(fn.body)) return ts.isCallExpression(unwrap(fn.body)) ? unwrap(fn.body) : null;
  const statements = fn.body.statements.filter((stmt) => !ts.isEmptyStatement(stmt));
  if (
    statements.length !== 1 ||
    !ts.isReturnStatement(statements[0]) ||
    !statements[0].expression
  ) {
    return null;
  }
  const expr = unwrap(statements[0].expression);
  return expr && ts.isCallExpression(expr) ? expr : null;
}

function isFnExported(fn) {
  if (hasExport(fn)) return true;
  let current = fn;
  while (
    current.parent &&
    (ts.isParenthesizedExpression(current.parent) ||
      ts.isAsExpression(current.parent) ||
      ts.isSatisfiesExpression(current.parent) ||
      ts.isTypeAssertionExpression(current.parent) ||
      ts.isNonNullExpression(current.parent))
  ) {
    current = current.parent;
  }
  const parent = current.parent;
  if (parent && ts.isVariableDeclaration(parent) && parent.initializer === current) {
    const list = parent.parent;
    const stmt = list && list.parent;
    if (stmt && ts.isVariableStatement(stmt) && hasExport(stmt)) return true;
  }
  if (parent && ts.isExportAssignment(parent)) return true;
  return false;
}

function hasExport(node) {
  return (node.modifiers ?? []).some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword);
}

function recordLoose(node, symbol, source, rel, ctx) {
  recordImport(node, source, rel, ctx);
  if (owned(ctx.owners, 'workspace-access-denial', rel)) return;
  if (literalText(node) === DENIAL_CODE && inThrowOrReturn(node) && !inEquality(node)) {
    bump(
      ctx.findings.D1,
      `${rel} :: ${symbol} :: auth-code:${DENIAL_CODE}`,
      site(rel, lineOf(source, node), 1, hint('workspace-access-denial', ctx.owners))
    );
  }
}

function applyDigest(item, canonicalNames, source, rel, ctx) {
  const origins = digestOrigins(item.node, canonicalNames, source);
  let framing = 0;
  let firstLine = item.line;
  for (const origin of origins.values()) {
    if (!origin.framing) continue;
    framing += 1;
    firstLine = Math.min(firstLine, origin.line);
  }
  if (framing > 0 && !owned(ctx.owners, 'digest-framing', rel)) {
    const key = `${rel} :: ${item.symbol} :: digest-framing`;
    const prev = ctx.findings.D1[key];
    if (prev) prev.value += framing;
    else ctx.findings.D1[key] = site(rel, firstLine, framing, hint('digest-framing', ctx.owners));
  }
}

function digestOrigins(fn, canonicalNames, source) {
  const jsonIds = new Set();
  const hashIds = new Map();
  const origins = new Map();
  const visit = (node) => {
    if (node !== fn && isFn(node)) return;
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.initializer) {
      bindDigest(
        node.name.text,
        unwrap(node.initializer),
        jsonIds,
        hashIds,
        origins,
        canonicalNames,
        source
      );
    }
    if (isAssignment(node) && ts.isIdentifier(node.left)) {
      bindDigest(
        node.left.text,
        unwrap(node.right),
        jsonIds,
        hashIds,
        origins,
        canonicalNames,
        source
      );
    }
    if (isCreateHashCall(node) && !origins.has(node)) {
      origins.set(node, { framing: false, line: lineOf(source, node), arg: 'none' });
    }
    if (isUpdateCall(node)) {
      const origin = resolveHash(node.expression.expression, hashIds, origins, source);
      const arg = node.arguments[0] ? unwrap(node.arguments[0]) : null;
      if (origin && isJsonExpr(arg, jsonIds, canonicalNames)) {
        const state = origins.get(origin);
        state.framing = true;
        state.arg = describeArg(arg);
      } else if (origin && stateArgEmpty(origins, origin)) {
        origins.get(origin).arg = describeArg(arg);
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(fn);
  return origins;
}

function stateArgEmpty(origins, origin) {
  return origins.get(origin).arg === 'none';
}

function bindDigest(name, init, jsonIds, hashIds, origins, canonicalNames, source) {
  if (!init) return;
  if (isJsonExpr(init, jsonIds, canonicalNames)) jsonIds.add(name);
  const origin = resolveHash(init, hashIds, origins, source);
  if (origin) hashIds.set(name, origin);
}

function resolveHash(node, hashIds, origins, source) {
  if (!node) return null;
  node = unwrap(node);
  if (!node) return null;
  if (ts.isIdentifier(node)) return hashIds.get(node.text) ?? null;
  if (isCreateHashCall(node)) {
    if (!origins.has(node))
      origins.set(node, { framing: false, line: lineOf(source, node), arg: 'none' });
    return node;
  }
  if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression)) {
    const name = node.expression.name.text;
    if (name === 'update' || name === 'digest' || name === 'copy') {
      return resolveHash(node.expression.expression, hashIds, origins, source);
    }
  }
  return null;
}

function isJsonExpr(node, jsonIds, canonicalNames) {
  if (!node) return false;
  node = unwrap(node);
  if (!node) return false;
  if (ts.isIdentifier(node)) return jsonIds.has(node.text);
  if (isJsonStringify(node)) return true;
  if (!ts.isCallExpression(node)) return false;
  const expr = unwrap(node.expression);
  if (expr && ts.isIdentifier(expr) && canonicalNames.has(expr.text)) return true;
  if (expr && ts.isPropertyAccessExpression(expr) && canonicalNames.has(expr.name.text))
    return true;
  return false;
}

function describeArg(node) {
  if (!node) return 'none';
  if (ts.isIdentifier(node)) return `id:${node.text}`;
  if (isJsonStringify(node)) return 'stringify';
  if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression)) {
    return `call:${node.expression.name.text}`;
  }
  if (ts.isCallExpression(node) && ts.isIdentifier(node.expression))
    return `call:${node.expression.text}`;
  return ts.SyntaxKind[node.kind] ?? 'expr';
}

function functionHasCreateHash(fn) {
  let found = false;
  const visit = (node) => {
    if (found || (node !== fn && isFn(node))) return;
    if (isCreateHashCall(node)) found = true;
    else tsForEach(node, visit);
  };
  visit(fn);
  return found;
}

function tsForEach(node, visit) {
  node.forEachChild(visit);
}

function isUpdateCall(node) {
  return (
    ts.isCallExpression(node) &&
    ts.isPropertyAccessExpression(node.expression) &&
    node.expression.name.text === 'update'
  );
}

function isAssignment(node) {
  return ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.EqualsToken;
}

function isJsonStringify(node) {
  return (
    ts.isCallExpression(node) &&
    ts.isPropertyAccessExpression(node.expression) &&
    node.expression.name.text === 'stringify' &&
    ts.isIdentifier(node.expression.expression) &&
    node.expression.expression.text === 'JSON'
  );
}

function isCreateHashCall(node) {
  if (!ts.isCallExpression(node)) return false;
  const expr = node.expression;
  return (
    (ts.isIdentifier(expr) && expr.text === 'createHash') ||
    (ts.isPropertyAccessExpression(expr) && expr.name.text === 'createHash')
  );
}

function recordImport(node, source, rel, ctx) {
  const line = lineOf(source, node);
  if (ts.isImportDeclaration(node)) {
    const spec = literalText(node.moduleSpecifier);
    if (spec === null) return;
    const clause = node.importClause;
    if (!clause) return ctx.valueImports.push({ from: rel, spec, line });
    if (clause.isTypeOnly) return;
    const kinds = namedKinds(clause.name ? [false] : [], clause.namedBindings);
    if (clause.name || kinds.value) ctx.valueImports.push({ from: rel, spec, line });
    return;
  }
  if (ts.isExportDeclaration(node) && node.moduleSpecifier) {
    const spec = literalText(node.moduleSpecifier);
    if (spec === null) return;
    if (node.isTypeOnly) return;
    const kinds =
      node.exportClause && ts.isNamedExports(node.exportClause)
        ? namedKinds([], node.exportClause)
        : { value: true, type: false };
    if (kinds.value) ctx.valueImports.push({ from: rel, spec, line });
    return;
  }
  if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
    const spec = literalText(node.arguments[0]);
    if (spec !== null) ctx.valueImports.push({ from: rel, spec, line });
  }
}

function namedKinds(seed, bindings) {
  let value = false;
  let type = false;
  const host = bindings ?? null;
  const elements = host && host.elements && isNamedBindings(host) ? host.elements : [];
  if (host && ts.isNamespaceImport(host)) value = true;
  for (const element of elements) {
    if (element.isTypeOnly) type = true;
    else value = true;
  }
  if (seed.some(Boolean)) value = true;
  return { value, type };
}

function isNamedBindings(host) {
  return ts.isNamedImports(host) || ts.isNamedExports(host);
}

function scanScale(root, symbol, source, rel, findings) {
  const scopes = [new Map()];
  visit(root);
  function visit(node) {
    if (node !== root && isFn(node)) return;
    const scoped = opensScope(node);
    if (scoped) scopes.push(new Map());
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && isConstOrLet(node)) {
      scopes.at(-1).set(node.name.text, node.initializer ? listMethodOf(node.initializer) : null);
    }
    if (isIteratorCall(node)) {
      const list = iteratorList(node, scopes);
      if (list) {
        bump(
          findings.D6,
          `${rel} :: ${symbol} :: ${list}.${node.expression.name.text}`,
          site(rel, lineOf(source, node), 1, HINT.D6)
        );
      }
    }
    node.forEachChild(visit);
    if (scoped) scopes.pop();
  }
}

function listMethodOf(node) {
  const init = unwrap(node);
  if (!init || !init.expression) return null;
  if (!ts.isCallExpression(init)) return null;
  return listMethodName(init);
}

function isIteratorCall(node) {
  return (
    ts.isCallExpression(node) &&
    ts.isPropertyAccessExpression(node.expression) &&
    ITERATORS.has(node.expression.name.text)
  );
}

function iteratorList(node, scopes) {
  const receiver = unwrap(node.expression.expression);
  if (receiver && ts.isCallExpression(receiver)) return listMethodName(receiver);
  if (receiver && ts.isIdentifier(receiver)) return lookupScope(scopes, receiver.text);
  return null;
}

function lookupScope(scopes, name) {
  for (let index = scopes.length - 1; index >= 0; index -= 1) {
    if (scopes[index].has(name)) return scopes[index].get(name);
  }
  return null;
}

function resolveEdges(imports, fileSet) {
  const edges = new Map();
  const lines = new Map();
  for (const file of fileSet) edges.set(file, new Set());
  for (const item of imports) {
    if (!item.spec.startsWith('.')) continue;
    const target = resolveSpecifier(item.from, item.spec, fileSet);
    if (!target) continue;
    edges.get(item.from).add(target);
    const key = `${item.from} -> ${target}`;
    if (!lines.has(key)) lines.set(key, item.line);
  }
  edges.lines = lines;
  return edges;
}

function posixDir(file) {
  const slash = file.lastIndexOf('/');
  return slash === -1 ? '' : file.slice(0, slash);
}

function posixJoin(dir, spec) {
  const parts = [];
  for (const part of `${dir}/${spec}`.split('/')) {
    if (part === '' || part === '.') continue;
    if (part === '..') parts.pop();
    else parts.push(part);
  }
  return parts.join('/');
}

function resolveSpecifier(fromFile, spec, fileSet) {
  const raw = posixJoin(posixDir(fromFile), spec);
  const candidates = [];
  const stem = raw.replace(/\.(?:js|mjs)$/, '');
  if (raw.endsWith('.js') || raw.endsWith('.mjs')) {
    candidates.push(
      `${stem}.ts`,
      `${stem}.tsx`,
      `${stem}.mts`,
      `${stem}/index.ts`,
      `${stem}/index.tsx`
    );
  } else if (/\.(?:ts|tsx|mts)$/.test(raw)) candidates.push(raw);
  else
    candidates.push(`${raw}.ts`, `${raw}.tsx`, `${raw}.mts`, `${raw}/index.ts`, `${raw}/index.tsx`);
  return candidates.find((candidate) => fileSet.has(candidate)) ?? null;
}

function addCycles(findings, edges, sccs) {
  const member = new Map();
  sccs.forEach((component, index) => {
    for (const file of component) member.set(file, index);
  });
  for (const [from, targets] of edges) {
    for (const target of targets) {
      if (member.get(from) !== member.get(target)) continue;
      setOnce(
        findings.D2,
        `${from} -> ${target}`,
        site(from, edges.lines.get(`${from} -> ${target}`) ?? 1, 1, HINT.D2)
      );
    }
  }
}

function tarjan(nodes, edges) {
  let index = 0;
  const indices = new Map();
  const low = new Map();
  const stack = [];
  const onStack = new Set();
  const components = [];
  const strong = (node) => {
    indices.set(node, index);
    low.set(node, index);
    index += 1;
    stack.push(node);
    onStack.add(node);
    for (const next of edges.get(node) ?? []) {
      if (!indices.has(next)) {
        strong(next);
        low.set(node, Math.min(low.get(node), low.get(next)));
      } else if (onStack.has(next)) low.set(node, Math.min(low.get(node), indices.get(next)));
    }
    if (low.get(node) !== indices.get(node)) return;
    const component = [];
    let item = null;
    while (item !== node) {
      item = stack.pop();
      onStack.delete(item);
      component.push(item);
    }
    components.push(component);
  };
  for (const node of nodes) if (!indices.has(node)) strong(node);
  return components;
}

function cognitive(fn) {
  const state = { score: 0 };
  visit(fn.body, 0);
  return state.score;

  function visit(node, nesting) {
    if (!node || isFn(node)) return;
    if (ts.isIfStatement(node)) return visitIf(node, nesting);
    if (ts.isConditionalExpression(node)) return visitTernary(node, nesting);
    if (ts.isSwitchStatement(node)) return visitSwitch(node, nesting);
    if (isLoop(node)) return visitLoop(node, nesting);
    if (ts.isCatchClause(node)) return visitCatch(node, nesting);
    if (isLogic(node)) return scoreLogic(node, nesting);
    ts.forEachChild(node, (child) => visit(child, nesting));
  }

  function visitIf(node, nesting) {
    state.score += 1 + nesting;
    visit(node.expression, nesting);
    visit(node.thenStatement, nesting + 1);
    let alt = node.elseStatement;
    while (alt && ts.isIfStatement(alt)) {
      state.score += 1;
      visit(alt.expression, nesting);
      visit(alt.thenStatement, nesting + 1);
      alt = alt.elseStatement;
    }
    if (alt) {
      state.score += 1;
      visit(alt, nesting + 1);
    }
  }

  function visitTernary(node, nesting) {
    state.score += 1 + nesting;
    visit(node.condition, nesting);
    visit(node.whenTrue, nesting + 1);
    visit(node.whenFalse, nesting + 1);
  }

  function visitSwitch(node, nesting) {
    state.score += 1 + nesting;
    visit(node.expression, nesting);
    visit(node.caseBlock, nesting + 1);
  }

  function visitLoop(node, nesting) {
    state.score += 1 + nesting;
    node.forEachChild((child) => visit(child, nesting + 1));
  }

  function visitCatch(node, nesting) {
    state.score += 1 + nesting;
    node.forEachChild((child) => visit(child, nesting + 1));
  }

  function scoreLogic(node, nesting) {
    walk(node, null);
    function walk(current, operator) {
      if (!isLogic(current)) return visit(current, nesting);
      const op = current.operatorToken.kind;
      let next = operator;
      if (op !== operator) {
        state.score += 1;
        next = op;
      }
      walk(current.left, next);
      walk(current.right, next);
    }
  }
}

function isLoop(node) {
  return (
    ts.isForStatement(node) ||
    ts.isForInStatement(node) ||
    ts.isForOfStatement(node) ||
    ts.isWhileStatement(node) ||
    ts.isDoStatement(node)
  );
}

function isLogic(node) {
  if (!ts.isBinaryExpression(node)) return false;
  const kind = node.operatorToken.kind;
  return kind === ts.SyntaxKind.AmpersandAmpersandToken || kind === ts.SyntaxKind.BarBarToken;
}

function directInnerFunctions(fn) {
  const found = [];
  const body = fn.body;
  if (!body) return found;
  const visit = (node) => {
    if (isPlainFn(node)) {
      found.push(node);
      return;
    }
    if (isFn(node)) return;
    node.forEachChild(visit);
  };
  if (isPlainFn(body)) found.push(body);
  else body.forEachChild(visit);
  return found;
}

function isPlainFn(node) {
  return (
    ts.isFunctionDeclaration(node) || ts.isFunctionExpression(node) || ts.isArrowFunction(node)
  );
}

function buildFactoryUnit(fn, symbol, inners, rel, source, ctx) {
  const names = new Set(paramNames(fn));
  collectBodyBindings(fn.body, names);
  const labels = labelInners(inners);
  const sibling = new Set(labels);
  const nodes = inners.map((inner, index) => ({
    name: labels[index],
    resources: referencedNames(inner, names),
    calls: referencedCalls(inner, sibling, labels[index]),
  }));
  pushUnit(ctx, {
    file: rel,
    symbol,
    line: lineOf(source, fn),
    kind: 'factory',
    width: isFnExported(fn) ? 1 : 0,
    nodes,
  });
}

function labelInners(inners) {
  const used = new Set();
  return inners.map((inner, index) => {
    let label = '<anon>';
    if ((inner.name && inner.name.text) || bindingName(inner))
      label = inner.name?.text ?? bindingName(inner);
    if (!label) label = `<anon#${index + 1}>`;
    return uniqueLabel(label, used);
  });
}

function uniqueLabel(label, used) {
  if (!used.has(label)) {
    used.add(label);
    return label;
  }
  let index = 2;
  while (used.has(`${label}#${index}`)) index += 1;
  const next = `${label}#${index}`;
  used.add(next);
  return next;
}

function collectBodyBindings(body, names) {
  if (!body || !body.forEachChild) return;
  const visit = (node) => {
    if (isFn(node)) return;
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name)) names.add(node.name.text);
    if (ts.isFunctionDeclaration(node) && node.name) names.add(node.name.text);
    if (ts.isClassDeclaration(node) && node.name) names.add(node.name.text);
    node.forEachChild(visit);
  };
  body.forEachChild(visit);
}

function referencedNames(fn, names) {
  const found = new Set();
  walkRefs(fn, names, found, new Set());
  return found;
}

function referencedCalls(fn, names, self) {
  const found = new Set();
  walkCalls(fn, names, self, found);
  return found;
}

function walkRefs(fn, names, found, seedLocals) {
  const locals = new Set([...paramNames(fn), ...seedLocals]);
  if (fn.name) locals.add(fn.name.text);
  const visit = (node) => {
    if (node !== fn && isFn(node)) {
      walkRefs(node, names, found, locals);
      return;
    }
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name)) {
      if (node.initializer) visit(node.initializer);
      locals.add(node.name.text);
      return;
    }
    if (
      ts.isCatchClause(node) &&
      node.variableDeclaration &&
      ts.isIdentifier(node.variableDeclaration.name)
    ) {
      locals.add(node.variableDeclaration.name.text);
    }
    if (ts.isIdentifier(node) && names.has(node.text) && !locals.has(node.text))
      found.add(node.text);
    node.forEachChild(visit);
  };
  fn.forEachChild(visit);
}

function walkCalls(fn, names, self, found) {
  const visit = (node, locals) => {
    if (node !== fn && isFn(node)) {
      const next = new Set(locals);
      for (const name of paramNames(node)) next.add(name);
      if (node.name?.text) next.add(node.name.text);
      node.forEachChild((child) => visit(child, next));
      return;
    }
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name)) {
      if (node.initializer) visit(node.initializer, locals);
      locals.add(node.name.text);
      return;
    }
    if (
      ts.isCallExpression(node) &&
      ts.isIdentifier(node.expression) &&
      names.has(node.expression.text) &&
      node.expression.text !== self &&
      !locals.has(node.expression.text)
    ) {
      found.add(node.expression.text);
    }
    node.forEachChild((child) => visit(child, locals));
  };
  const locals = new Set(paramNames(fn));
  if (fn.name?.text) locals.add(fn.name.text);
  fn.forEachChild((child) => visit(child, locals));
}

function buildClassUnit(frame, rel, source, ctx) {
  const nodes = frame.methods
    .filter((method) => method.node.body)
    .map((method) => ({
      name: method.name,
      resources: method.fields,
      calls: method.calls,
    }));
  if (nodes.length === 0) return;
  pushUnit(ctx, {
    file: rel,
    symbol: frame.name,
    line: lineOf(source, frame.node),
    kind: 'class',
    width: publicMethods(frame.node),
    nodes,
  });
}

function addModuleUnit(source, rel, topLevel, ctx) {
  const bindings = moduleBindings(source);
  const labels = topLevel.map((item) => item.symbol);
  const callable = new Set(
    topLevel.filter((item) => item.kind === 'function').map((item) => item.symbol.split('.').at(-1))
  );
  const nodes = topLevel.map((item) => ({
    name: item.symbol,
    resources: referencedNames(item.node, bindings),
    calls: referencedCalls(item.node, callable, item.symbol.split('.').at(-1)),
  }));
  pushUnit(ctx, {
    file: rel,
    symbol: '<module>',
    line: 1,
    kind: 'module',
    width: countValueExports(source),
    nodes,
    labels,
  });
}

function moduleBindings(source) {
  const names = new Set();
  for (const stmt of source.statements) {
    if (ts.isFunctionDeclaration(stmt) && stmt.name) names.add(stmt.name.text);
    if (ts.isClassDeclaration(stmt) && stmt.name) names.add(stmt.name.text);
    if (ts.isEnumDeclaration(stmt)) names.add(stmt.name.text);
    if (ts.isVariableStatement(stmt)) {
      for (const decl of stmt.declarationList.declarations) {
        if (ts.isIdentifier(decl.name)) names.add(decl.name.text);
      }
    }
    if (ts.isImportDeclaration(stmt) && stmt.importClause && !stmt.importClause.isTypeOnly) {
      const clause = stmt.importClause;
      if (clause.name) names.add(clause.name.text);
      const bindings = clause.namedBindings;
      if (bindings && ts.isNamespaceImport(bindings)) names.add(bindings.name.text);
      if (bindings && ts.isNamedImports(bindings)) {
        for (const element of bindings.elements)
          if (!element.isTypeOnly) names.add(element.name.text);
      }
    }
  }
  return names;
}

function countValueExports(source) {
  let count = 0;
  for (const stmt of source.statements) {
    if (ts.isExportDeclaration(stmt)) count += exportDeclarationOutcome(stmt, new Set()).exports;
    else if (ts.isExportAssignment(stmt)) count += 1;
    else if (hasExport(stmt) && ts.isVariableStatement(stmt))
      count += stmt.declarationList.declarations.length;
    else if (
      hasExport(stmt) &&
      !ts.isInterfaceDeclaration(stmt) &&
      !ts.isTypeAliasDeclaration(stmt) &&
      (ts.isFunctionDeclaration(stmt) || ts.isClassDeclaration(stmt) || ts.isEnumDeclaration(stmt))
    ) {
      count += 1;
    }
  }
  return count;
}

function collectThis(fn) {
  const fields = new Set();
  const calls = new Set();
  const visit = (node) => {
    if (node !== fn && isFn(node) && !ts.isArrowFunction(node)) return;
    if (ts.isPropertyAccessExpression(node) && node.expression.kind === ts.SyntaxKind.ThisKeyword) {
      const name = propText(node.name);
      if (name) {
        if (ts.isCallExpression(node.parent) && node.parent.expression === node) calls.add(name);
        else fields.add(`field:${name}`);
      }
    }
    if (ts.isElementAccessExpression(node) && node.expression.kind === ts.SyntaxKind.ThisKeyword) {
      const arg = node.argumentExpression;
      if (arg && (ts.isStringLiteral(arg) || ts.isNoSubstitutionTemplateLiteral(arg))) {
        fields.add(`field:${arg.text}`);
      }
    }
    node.forEachChild(visit);
  };
  visit(fn);
  return { fields, calls };
}

function pushUnit(ctx, unit) {
  const hub = lcom4(unit.nodes).length;
  setMax(
    ctx.findings.D5,
    `${unit.file} :: ${unit.symbol} :: lcom4`,
    site(unit.file, unit.line, hub, HINT.D5)
  );
}

function lcom4(nodes) {
  return connect(nodes, new Set(hubResources(nodes)));
}

function hubResources(nodes) {
  const counts = new Map();
  for (const node of nodes) {
    const seen = new Set(node.resources);
    for (const callee of node.calls) seen.add(`call:${callee}`);
    for (const resource of seen) counts.set(resource, (counts.get(resource) ?? 0) + 1);
  }
  const limit = nodes.length / 2;
  return [...counts.entries()]
    .filter((entry) => entry[1] > limit)
    .map((entry) => entry[0])
    .sort();
}

function connect(nodes, dropped) {
  const parent = nodes.map((_, index) => index);
  const byName = new Map(nodes.map((node, index) => [node.name, index]));
  const find = (index) => {
    let cursor = index;
    while (parent[cursor] !== cursor) cursor = parent[cursor];
    let compress = index;
    while (parent[compress] !== cursor) {
      const next = parent[compress];
      parent[compress] = cursor;
      compress = next;
    }
    return cursor;
  };
  const unite = (left, right) => {
    const a = find(left);
    const b = find(right);
    if (a !== b) parent[b] = a;
  };
  const first = new Map();
  nodes.forEach((node, index) => {
    for (const resource of node.resources) {
      if (dropped.has(resource)) continue;
      if (first.has(resource)) unite(index, first.get(resource));
      else first.set(resource, index);
    }
    for (const callee of node.calls) {
      if (dropped.has(`call:${callee}`)) continue;
      const target = byName.get(callee);
      if (target !== undefined && target !== index) unite(index, target);
    }
  });
  const groups = new Map();
  nodes.forEach((node, index) => {
    const root = find(index);
    if (!groups.has(root)) groups.set(root, []);
    groups.get(root).push(node.name);
  });
  return [...groups.values()]
    .map((members) => members.sort())
    .sort((a, b) => b.length - a.length || (a[0] < b[0] ? -1 : 1));
}

function canonicalBody(fn) {
  const nodes = [];
  const keyIds = new Set();
  const visit = (node) => {
    if (node !== fn && isFn(node)) return;
    nodes.push(node);
    ts.forEachChild(node, visit);
  };
  visit(fn);
  for (const node of nodes) {
    if (
      ts.isVariableDeclaration(node) &&
      ts.isIdentifier(node.name) &&
      node.initializer &&
      isConstOrLet(node)
    ) {
      if (isObjectKeysCall(unwrap(node.initializer))) keyIds.add(node.name.text);
    }
  }
  let stringify = false;
  let keys = false;
  let sorted = false;
  let locale = false;
  for (const node of nodes) {
    if (!ts.isCallExpression(node) || !ts.isPropertyAccessExpression(node.expression)) continue;
    const name = node.expression.name.text;
    const receiver = node.expression.expression;
    if (name === 'stringify' && ts.isIdentifier(receiver) && receiver.text === 'JSON')
      stringify = true;
    if (name === 'localeCompare') locale = true;
    if (isObjectKeysCall(node)) keys = true;
    if (name === 'sort' && tracesToKeys(unwrap(receiver), keyIds)) sorted = true;
  }
  return stringify && (sorted || (locale && keys));
}

function tracesToKeys(node, keyIds) {
  if (!node) return false;
  if (isObjectKeysCall(node)) return true;
  if (ts.isIdentifier(node)) return keyIds.has(node.text);
  if (
    ts.isCallExpression(node) ||
    ts.isPropertyAccessExpression(node) ||
    ts.isParenthesizedExpression(node)
  ) {
    return tracesToKeys(node.expression, keyIds);
  }
  return false;
}

function isObjectKeysCall(node) {
  if (!node) return false;
  if (!ts.isCallExpression(node) || !ts.isPropertyAccessExpression(node.expression)) return false;
  const name = node.expression.name.text;
  const receiver = node.expression.expression;
  return (
    (name === 'keys' || name === 'entries') &&
    ts.isIdentifier(receiver) &&
    receiver.text === 'Object'
  );
}

function listMethodName(call) {
  const expr = call.expression;
  if (ts.isPropertyAccessExpression(expr) && LIST_METHOD.test(expr.name.text))
    return expr.name.text;
  if (ts.isIdentifier(expr) && LIST_METHOD.test(expr.text)) return expr.text;
  return null;
}

function declaredNames(node) {
  const names = [];
  if ((ts.isFunctionDeclaration(node) || ts.isFunctionExpression(node)) && node.name)
    names.push(node.name.text);
  if (ts.isMethodDeclaration(node) || ts.isGetAccessor(node) || ts.isSetAccessor(node)) {
    const text = propText(node.name);
    if (text) names.push(text);
  }
  const bound = bindingName(node);
  if (bound) names.push(bound);
  return names;
}

function fnSymbol(node, parent, anons) {
  if ((ts.isFunctionDeclaration(node) || ts.isFunctionExpression(node)) && node.name) {
    return joinSymbol(parent, node.name.text);
  }
  if (ts.isConstructorDeclaration(node)) return joinSymbol(parent, 'constructor');
  if (ts.isMethodDeclaration(node) || ts.isGetAccessor(node) || ts.isSetAccessor(node)) {
    return joinSymbol(parent, propText(node.name) ?? anon(parent, anons));
  }
  return joinSymbol(parent, bindingName(node) ?? anon(parent, anons));
}

function memberLabel(node) {
  if (ts.isConstructorDeclaration(node)) return 'constructor';
  return propText(node.name) ?? 'member';
}

function isClassMember(node) {
  return (
    ts.isMethodDeclaration(node) ||
    ts.isGetAccessor(node) ||
    ts.isSetAccessor(node) ||
    ts.isConstructorDeclaration(node)
  );
}

function bindingName(node) {
  let current = node;
  while (
    current.parent &&
    (ts.isParenthesizedExpression(current.parent) ||
      ts.isAsExpression(current.parent) ||
      ts.isSatisfiesExpression(current.parent) ||
      ts.isTypeAssertionExpression(current.parent) ||
      ts.isNonNullExpression(current.parent))
  ) {
    current = current.parent;
  }
  const parent = current.parent;
  if (!parent) return null;
  if (
    ts.isVariableDeclaration(parent) &&
    parent.initializer === current &&
    ts.isIdentifier(parent.name)
  ) {
    return parent.name.text;
  }
  if (
    (ts.isPropertyAssignment(parent) || ts.isPropertyDeclaration(parent)) &&
    parent.initializer === current
  ) {
    return propText(parent.name);
  }
  if (
    ts.isBinaryExpression(parent) &&
    parent.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
    parent.right === current
  ) {
    if (ts.isIdentifier(parent.left)) return parent.left.text;
    if (ts.isPropertyAccessExpression(parent.left)) return parent.left.name.text;
  }
  if (ts.isExportAssignment(parent)) return 'default';
  return null;
}

function publicMethods(node) {
  let count = 0;
  for (const member of node.members) {
    const method =
      ts.isMethodDeclaration(member) || ts.isGetAccessor(member) || ts.isSetAccessor(member);
    if (!method || !member.body || (member.name && ts.isPrivateIdentifier(member.name))) continue;
    const hidden = (member.modifiers ?? []).some(
      (modifier) =>
        modifier.kind === ts.SyntaxKind.PrivateKeyword ||
        modifier.kind === ts.SyntaxKind.ProtectedKeyword
    );
    if (!hidden) count += 1;
  }
  return count;
}

function paramNames(fn) {
  const names = [];
  for (const param of fn.parameters ?? []) collectBindingNames(param.name, names);
  return names;
}

function collectBindingNames(name, out) {
  if (!name) return;
  if (ts.isIdentifier(name)) out.push(name.text);
  else if (ts.isObjectBindingPattern(name) || ts.isArrayBindingPattern(name)) {
    for (const element of name.elements) {
      if (!ts.isBindingElement(element)) continue;
      if (element.propertyName && ts.isIdentifier(element.name)) out.push(element.name.text);
      else collectBindingNames(element.name, out);
    }
  }
}

function isFn(node) {
  return (
    ts.isFunctionDeclaration(node) ||
    ts.isFunctionExpression(node) ||
    ts.isArrowFunction(node) ||
    ts.isMethodDeclaration(node) ||
    ts.isConstructorDeclaration(node) ||
    ts.isGetAccessor(node) ||
    ts.isSetAccessor(node)
  );
}

function isIdentifier(node) {
  return ts.isIdentifier(node);
}

function opensScope(node) {
  return (
    ts.isBlock(node) ||
    ts.isModuleBlock(node) ||
    ts.isForStatement(node) ||
    ts.isForOfStatement(node) ||
    ts.isForInStatement(node) ||
    ts.isCatchClause(node) ||
    ts.isCaseClause(node) ||
    ts.isDefaultClause(node)
  );
}

function isConstOrLet(node) {
  const list = node.parent;
  return Boolean(
    list &&
      ts.isVariableDeclarationList(list) &&
      ((list.flags & ts.NodeFlags.Const) !== 0 || (list.flags & ts.NodeFlags.Let) !== 0)
  );
}

function unwrap(node) {
  let current = node;
  while (
    current &&
    (ts.isAwaitExpression(current) ||
      ts.isParenthesizedExpression(current) ||
      ts.isAsExpression(current) ||
      ts.isSatisfiesExpression(current) ||
      ts.isNonNullExpression(current) ||
      ts.isTypeAssertionExpression(current))
  ) {
    current = current.expression;
  }
  return current;
}

function inThrowOrReturn(node) {
  for (let current = node.parent; current; current = current.parent) {
    if (ts.isThrowStatement(current) || ts.isReturnStatement(current)) return true;
    if (isFn(current) || ts.isClassStaticBlockDeclaration(current)) return false;
  }
  return false;
}

function inEquality(node) {
  const kinds = [
    ts.SyntaxKind.EqualsEqualsEqualsToken,
    ts.SyntaxKind.EqualsEqualsToken,
    ts.SyntaxKind.ExclamationEqualsEqualsToken,
    ts.SyntaxKind.ExclamationEqualsToken,
  ];
  for (let current = node.parent; current; current = current.parent) {
    if (ts.isThrowStatement(current) || ts.isReturnStatement(current) || isFn(current))
      return false;
    if (ts.isBinaryExpression(current) && kinds.includes(current.operatorToken.kind)) return true;
  }
  return false;
}

function literalText(node) {
  if (!node) return null;
  return ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node) ? node.text : null;
}

function propText(name) {
  if (!name) return null;
  if (
    ts.isIdentifier(name) ||
    ts.isPrivateIdentifier(name) ||
    ts.isStringLiteral(name) ||
    ts.isNumericLiteral(name)
  ) {
    return name.text;
  }
  return null;
}

function joinSymbol(parent, name) {
  return !parent || parent === '<module>' ? name : `${parent}.${name}`;
}

function anon(parent, state) {
  const key = parent || '<module>';
  const next = (state.get(key) ?? 0) + 1;
  state.set(key, next);
  return `<anon#${next}>`;
}

function owned(owners, primitive, file) {
  return (owners[primitive] ?? []).includes(file);
}

function hint(primitive, owners) {
  const list = owners[primitive] ?? [];
  return `use the ${primitive} owner ${list.length > 0 ? list.join(', ') : '(owner not yet chosen)'}`;
}

function lineOf(source, node) {
  return source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1;
}

function site(file, line, value, hintText) {
  return { file, line, value, hint: hintText };
}

function bump(bucket, key, item) {
  const prev = bucket[key];
  if (prev) prev.value += 1;
  else bucket[key] = item;
}

function setOnce(bucket, key, item) {
  if (!bucket[key]) bucket[key] = item;
}

function setMax(bucket, key, item) {
  if (!bucket[key] || item.value > bucket[key].value) bucket[key] = item;
}

function deltaOf(detector, key, item, base) {
  if (!Object.hasOwn(base, key)) return { detector, key, kind: 'new', ...item };
  if (item.value > base[key]) return { detector, key, kind: 'grew', baseline: base[key], ...item };
  return null;
}

function readBaseline(file) {
  const parsed = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {};
  const baseline = emptyBaseline();
  for (const detector of BLOCKING) baseline[detector] = parsed[detector] ?? {};
  return baseline;
}

function writeBaseline(file, baseline) {
  writeFileSync(file, `${JSON.stringify(baseline, null, 2)}\n`);
}

function formatDelta(item) {
  const growth = item.kind === 'grew' ? ` ${item.baseline} -> ${item.value}` : '';
  return `${item.file}:${item.line} ${item.detector}${growth} ${item.hint}`;
}

/** Top Signal items by value; read by reviewers and auditors, never compared with a baseline. */
function renderReport(findings, top = 20) {
  const lines = [];
  for (const detector of SIGNALS) {
    const items = Object.entries(findings[detector])
      .sort(([ka, a], [kb, b]) => b.value - a.value || (ka < kb ? -1 : 1))
      .slice(0, top);
    lines.push(`${detector} ${HINT[detector]}: ${Object.keys(findings[detector]).length} items`);
    for (const [key, item] of items) lines.push(`  ${item.value} ${item.file}:${item.line} ${key}`);
  }
  return `${lines.join('\n')}\n`;
}

